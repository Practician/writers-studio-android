/** Сколько решений листа уходит в промпт сцены: 3–5, по правилу sepia. */
export const ARCHITECTURE_DECISIONS_IN_PROMPT = 5;

/** Разбор ответа модели в лист. Мусор и выдумки отбрасываются. */
export function parseArchitectureSheet(value: unknown): ArchitectureSheet {
  const raw = value && typeof value === "object" ? (value as Record<string, unknown>) : {};
  const sheet: ArchitectureSheet = {};
  for (const field of ARCHITECTURE_FIELDS) {
    const answer = String(raw[field.id] ?? "").trim();
    if (!answer) continue;
    // Ответ принимаем, только если он близок к одному из вариантов: иначе это
    // не выбор из листа, а новое изобретение модели, которое нечем проверять.
    const match = field.choices.find((choice) => answer.toLowerCase().startsWith(choice.slice(0, 8).toLowerCase()))
      ?? field.choices.find((choice) => answer.toLowerCase().includes(choice.slice(0, 6).toLowerCase()));
    if (match) sheet[field.id] = match;
  }
  return sheet;
}

/** Лист, который удалось заполнить. Пустой лист — значит модель не ответила. */
export function architectureSheetCompleteness(sheet: ArchitectureSheet): number {
  return Math.round((Object.keys(sheet).length / ARCHITECTURE_FIELDS.length) * 100);
}

/** Полный блок промпта для агента-архитектора. */
