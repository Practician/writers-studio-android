/**
 * АГЕНТ-АРХИТЕКТОР: лист архитектуры главы до написания.
 *
 * Зачем отдельный агент. До сборки 114 форма главы задавалась каталогом из 21
 * приёма, из которого выбиралось 3–5 по seed. Это не архитектура, а список
 * запретов: ни один параметр формы главы не был ни задан, ни измерен, ни
 * обоснован. Между тем sepia (README: «Fiction gets its narrative architecture
 * repaired before anyone touches word choice») и StoryScope
 * (arXiv:2604.03136, 61 608 историй) говорят одно: различает человека и модель
 * именно форма — тематическая недоопределённость, разрыв причинной цепи,
 * способ развязки, режим эмоции, число локаций. Поверхностная правка в условии
 * LAMP сдвинула детектор лишь с 95,5 % до 93,9 %.
 *
 * Лист заполняется ОДИН раз на главу, до первого бита, и дальше только
 * читается: архитектура — свойство главы, а не абзаца. Модель получает
 * двенадцать полей с человеческими целями (не с запретами) и обязана выбрать по
 * одному значению в каждом — это форма «листа архитектуры» из
 * `narrative-pass.md`, где каждое поле помечено измеренным человеческим
 * диапазоном.
 *
 * Калибровка намеренно унаследована от принципа sepia: «Calibrate to the human
 * distribution, don't invert the AI one. The skill selects 3–5 moves per story and
 * leaves slack». Поэтому в промпт сцены уходит НЕ весь лист, а 3–5 решений:
 * глава, где применены все двенадцать, — это новый отпечаток, ровно тот
 * over-correction, о котором предупреждает rubric.md.
 */

export type ArchitectureChoice = string;

