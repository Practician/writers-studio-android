/**
 * Гл.6 под Yandex: база «чистый-русский» (~0% AI),
 * opening-стык, кольца, лёгкая дедупликация, финал без активации ладони.
 */
import fs from "node:fs";
import path from "node:path";

const basePath = path.join(
  path.resolve(".."),
  "Главы",
  "Глава-6-Число-20-очеловеченная",
  "глава-6-чистый-русский.txt",
);

let text = fs.readFileSync(basePath, "utf8");

const opening = `Правый коридор был темнее, чем петля за спиной. На стене у угла осталась бледно-синяя диагональ — символ отмены, который я вырезал ключом, когда злился и почти не держался на ногах. Я шагнул навстречу запаху мяты и меда. Жажда и голод еще были. Телефон в кармане держал около двух процентов, и я боялся лишний раз включать экран.

Пройдя несколько десятков шагов по пологому спуску, я увидел, что зеленоватое пятно вдали стало ярче. Это придало мне сил, и я ускорил шаг. Спуск был все еще пологий, и я смог бы побежать, если бы ноги не были такими тяжелыми. Но главное — я все еще чувствовал жажду и голод. Вспомнив о телефоне, достал его из кармана и включил. Заряд был на уровне 2%, а экран показывал только время 3 часа 47 минут.`;

text = text.replace(/^Начну снова\.[\s\S]*?3 часа 47 минут\./u, opening);

const rings = `Я присел и внимательнее посмотрел на линии на полу. Там лежали три кольца, одно в другом. Я начал считать сектора на внешнем и сбился, потом посчитал снова и получил двенадцать. На среднем тоже двенадцать. На внутреннем столько же. Я тронул внешнее, и оно поехало. Мягко, без скрипа. Провернул по часовой — число 20 стало тусклее. Среднее крутанул назад, против часовой — вспыхнуло ярче. Внутреннее почти не шло. Я навалился, сдвинул, и число почти погасло, даже стало меньше.

Я подумал, что это похоже на набор, а не на кнопку. Яркость менялась, когда я крутил. Если получалось удачнее — число росло и светило сильнее. Если нет — падало к нулю. Максимум — двадцать. Мне нужно было поймать именно яркую двадцатку.

Я крутил медленно и смотрел. На кольцах были мелкие бугорки, на стене — тонкая риска, сначала я принял ее за трещину. Подгонял внешнее к риске, среднее к внешнему, внутреннее к среднему со сдвигом. Несколько раз сбивался и начинал заново. Пальцы устали. Потом число снова стало ярким и ровным: 20.`;

if (!text.includes("яркую двадцатку")) {
  text = text.replace(
    /(концентрических окружностей и радиальных линий\.)/u,
    `$1\n\n${rings}`,
  );
}

text = text
  .replace(/\s*И стоял человек, но я его не видел\./gu, "")
  .replace(/своего рода /gu, "")
  .replace(/Но главное я не чувствовал жажды и голода\./g, "Но главное — жажда и голод все еще держали меня.");

// дедуп абзацев (режет тройные копии, оставляет первый)
const paras = text.split(/\n\n+/);
const seen = new Set<string>();
const kept: string[] = [];
for (const raw of paras) {
  const p = raw.trim();
  if (!p) continue;
  const key = p.replace(/\s+/g, " ").slice(0, 140);
  if (key.length > 50 && seen.has(key)) continue;
  // выкинуть второй-третий цикл «активации отпечатка / шум песка»
  if (
    kept.some((k) => k.includes("шевелилась песок") || k.includes("шевелился песок")) &&
    (p.includes("шевелилась песок") || p.includes("шевелился песок") || p.includes("Это что, активация"))
  ) {
    continue;
  }
  if (key.length > 50) seen.add(key);
  kept.push(p);
}
text = kept.join("\n\n");

// финал: если отпечаток «исчез» — смягчить крючком
if (/отпечаток ладони исчез/i.test(text)) {
  text = text.replace(
    /отпечаток ладони исчез[\s\S]*$/i,
    `отпечаток ладони остался на месте.

Я не стал жать его снова. Не сейчас. Сначала нужно было отдышаться. Заряд двадцать процентов. Голод и жажда ушли. Кольца почти погасли. Отпечаток никуда не денется — им займусь, когда буду готов.
`,
  );
} else if (!/Не сейчас/i.test(text)) {
  text += `

Я снова подошел к отпечатку ладони, но не прижал руку. Тепло от стены было слабым. Не сейчас. Сначала нужно было отдышаться. Заряд двадцать процентов. Голод и жажда ушли. Кольца почти погасли. Отпечаток никуда не денется — им займусь, когда буду готов.
`;
}

text = text.replace(/\n{3,}/g, "\n\n").trim() + "\n";

const outs = [
  path.join("src", "data", "labyrinth", "chapter-6.txt"),
  path.join("test-artifacts", "chapter6-optimal", "глава-6-optimal.txt"),
  path.join("test-artifacts", "chapter6", "глава-6-optimal.txt"),
  path.join("test-artifacts", "chapter6", "глава-6-финал.txt"),
  path.join("test-artifacts", "chapter6", "глава-6.txt"),
];
for (const p of outs) {
  fs.mkdirSync(path.dirname(p), { recursive: true });
  fs.writeFileSync(p, text, "utf8");
}
fs.writeFileSync(
  path.join("src", "data", "labyrinth", "chapter-6.content.ts"),
  `const text = ${JSON.stringify(text)};\nexport default text;\n`,
);

console.log("words", text.split(/\s+/).filter(Boolean).length);
