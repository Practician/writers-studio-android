/**
 * Минимальные правки поверх «чистый-русский» (0% Yandex).
 * Без 3:47. Без тройных «и что дальше». Канон: стык, кольца, 2%→20%.
 */
import fs from "node:fs";
import path from "node:path";

const basePath = path.join(
  path.resolve(".."),
  "Главы",
  "Глава-6-Число-20-очеловеченная",
  "глава-6-чистый-русский.txt",
);
let text = fs.readFileSync(basePath, "utf8");

// 1) Стык вместо «Начну снова» + 20% / без времени
const opening = `Правый коридор был темнее, чем петля за спиной. На стене у угла осталась бледно-синяя диагональ — символ отмены, который я вырезал ключом, когда злился и почти не держался на ногах. Я шагнул навстречу запаху мяты и меда. Жажда и голод еще были. Телефон в кармане держал около двух процентов, и я боялся лишний раз включать экран.

Пройдя несколько десятков шагов по пологому спуску, я увидел, что зеленоватое пятно вдали стало ярче. Это придало мне сил, и я ускорил шаг. Спуск был все еще пологий, и я смог бы побежать, если бы ноги не были такими тяжелыми. Но главное — я все еще чувствовал жажду и голод. Вспомнив о телефоне, достал его из кармана и включил. Заряд был на уровне 2%, а экран почти ничего не показывал. Только батарея.`;

text = text.replace(/^Начну снова\.[\s\S]*?3 часа 47 минут\./u, opening);

// 2) Кольца
const rings = `Я присел и внимательнее посмотрел на линии на полу. Там лежали три кольца, одно в другом. Я начал считать сектора на внешнем и сбился, потом посчитал снова и получил двенадцать. На среднем тоже двенадцать. На внутреннем столько же. Я тронул внешнее, и оно поехало. Мягко, без скрипа. Провернул по часовой — число 20 стало тусклее. Среднее крутанул назад, против часовой — вспыхнуло ярче. Внутреннее почти не шло. Я навалился, сдвинул, и число почти погасло, даже стало меньше.

Я подумал, что это похоже на набор, а не на кнопку. Яркость менялась, когда я крутил. Если получалось удачнее — число росло и светило сильнее. Если нет — падало к нулю. Максимум — двадцать. Мне нужно было поймать именно яркую двадцатку.

Я крутил медленно и смотрел. На кольцах были мелкие бугорки, на стене — тонкая риска, сначала я принял ее за трещину. Подгонял внешнее к риске, среднее к внешнему, внутреннее к среднему со сдвигом. Несколько раз сбивался и начинал заново. Пальцы устали. Потом число снова стало ярким и ровным: 20.`;

if (!text.includes("яркую двадцатку")) {
  text = text.replace(
    /(концентрических окружностей и радиальных линий\.)/u,
    `$1\n\n${rings}`,
  );
}

// 3) Мусор базы
text = text
  .replace(/\s*И стоял человек, но я его не видел\./gu, "")
  .replace(/своего рода /gu, "")
  .replace(
    /Выйдя из тупика, я увидел длинный коридор\.[\s\S]*?управлял всей площадкой\.\s*/u,
    "Я остался на площадке и пошел вдоль стены. Никаких окон. Только зеленоватое число и линии на полу.\n\n",
  )
  .replace(/Но главное я не чувствовал жажды и голода\./g, "Но главное — я все еще чувствовал жажду и голод.");

// 4) Убрать уход «вниз / свет вдалеке / неизвестность» (ломает тупик)
text = text.replace(
  /\nЯ пошел по пандусу, который все еще вел меня вниз[\s\S]*?любому развитию событий\.\s*/u,
  "\n",
);

// 5) Срезать ТОЛЬКО повторные блоки «песок / активация» (оставить первый)
{
  const paras = text.split(/\n\n+/);
  let sand = 0;
  text = paras
    .filter((p) => {
      if (/шевелил[а-я]* песок|Это что, активация/i.test(p)) {
        sand += 1;
        return sand === 1;
      }
      return true;
    })
    .join("\n\n");
}

// 6) Сократить «И что дальше» до 2 вхождений (не ноль — стиль базы)
{
  let count = 0;
  text = text.replace(/И что дальше\?/g, (m) => {
    count += 1;
    return count <= 2 ? m : "Что дальше?";
  });
}

// 7) Отпечаток не исчезает навсегда — крючок
text = text.replace(
  /отпечаток ладони, который светился ярко, внезапно исчез\./giu,
  "отпечаток ладони, который светился ярко, снова стал смутным, но остался на стене.",
);
text = text.replace(
  /смотрел на пустое место, где был отпечаток ладони/giu,
  "смотрел на отпечаток ладони",
);

if (!/Не сейчас/i.test(text)) {
  text += `

Я снова подошел к отпечатку, но не прижал руку. Тепло от стены было слабым. Не сейчас. Заряд двадцать процентов. Голод и жажда ушли. Кольца почти погасли. Отпечаток никуда не денется — им займусь, когда буду готов.
`;
}

// 8) Время
text = text
  .replace(/3:47/g, "")
  .replace(/\d+\s*часа\s*\d+\s*минут/giu, "")
  .replace(/только время[^.]*\./giu, "только батарея.")
  .replace(/\n{3,}/g, "\n\n")
  .trim() + "\n";

const words = text.split(/\s+/).filter(Boolean).length;
const ya = [...text.matchAll(/(?:^|[^а-яёА-ЯЁ])([Яя])(?=[^а-яёА-ЯЁ]|$)/g)].length;
const timeHits = text.match(/3:47|3 часа 47|только время \d/gi) || [];
const iqd = (text.match(/И что дальше/g) || []).length;

const outs = [
  path.join("src", "data", "labyrinth", "chapter-6.txt"),
  path.join("test-artifacts", "chapter6-optimal", "глава-6-optimal.txt"),
  path.join("test-artifacts", "chapter6", "глава-6-optimal.txt"),
  path.join("test-artifacts", "chapter6", "глава-6-финал.txt"),
  path.join("test-artifacts", "chapter6", "глава-6.txt"),
];
for (const p of outs) {
  fs.mkdirSync(path.dirname(p), { recursive: true });
  fs.writeFileSync(p, text, "utf8");
}
fs.writeFileSync(
  path.join("src", "data", "labyrinth", "chapter-6.content.ts"),
  `const text = ${JSON.stringify(text)};\nexport default text;\n`,
);

console.log(
  JSON.stringify(
    { words, ya, yaPer100: +(100 * ya / words).toFixed(2), timeHits: timeHits.length, iqd },
    null,
    2,
  ),
);
